      <section id="conclusion">
        <h2>The Practitioner's View</h2>
        <p>African renewable energy investment is entering a phase of genuine legal complexity. The first generation of projects was structured when bilateral BITs were relatively uniform, regulatory frameworks for renewables were new, and the Paris Agreement had not yet reshaped how states articulate their energy policy objectives. None of those conditions still apply.</p>
        <p>The disputes that will reach arbitral tribunals over the next five years — feed-in tariff adjustments, grid access revisions, PPA breaches by fiscally constrained state utilities — will be resolved by the intersection of contract drafting, BIT selection, and corporate structuring decisions made years earlier. The investors who will navigate this environment successfully are those who treated the treaty layer not as an afterthought but as an integral part of the investment architecture from the outset.</p>
        <p>The practical implication is straightforward: the questions raised in this article — which BIT applies, whether the FET clause is autonomous, whether an umbrella clause covers the PPA, what the economic equilibrium mechanism says — are not litigation questions. They are transaction questions. They should be answered before financial close, not after a tariff cut.</p>

