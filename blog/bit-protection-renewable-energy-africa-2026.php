      <section id="fet-standard">
        <h2>The FET Standard: Where the Dispute Is Won or Lost</h2>
        <p>The Fair and Equitable Treatment clause is the most frequently invoked BIT protection in energy sector disputes — and the most misunderstood. In the early 2000s, FET was interpreted broadly to impose a general obligation of regulatory stability. The wave of Spanish solar cases in the 2010s produced a significant correction: tribunals began requiring much more precision in identifying what specifically the state had done to breach the standard.</p>

        <h3>Legitimate expectations: what tribunals actually require</h3>
        <p>The concept of <strong>legitimate expectations</strong> sits at the heart of most FET claims. An investor argues that the state's regulatory change frustrated expectations that were reasonable at the time of the investment and induced by the state's own conduct. In renewable energy disputes, this typically means a state that promised a fixed twenty-year feed-in tariff and then cut it after the investor had committed capital.</p>
        <p>Modern tribunals — particularly post-<em>Blusun v. Italy</em> (2016) and the subsequent wave of intra-EU arbitration — have significantly narrowed the threshold. The investor must demonstrate not merely that it expected regulatory stability in general, but that the state made <strong>specific, targeted assurances</strong> to this investor — through legislation, individual permits, direct communications, or investment promotion — that were intended to induce the investment and on which the investor actually relied. A general regulatory framework that attracted the investment is ordinarily insufficient without something more specific.</p>

        <div class="takeaway">
          In an African context, the due diligence question cuts both ways. A tribunal will ask whether the investor examined the host state's regulatory history before committing capital. If a state has a documented history of tariff adjustments or grid access revisions, an investor's claim to have expected a fixed twenty-year tariff to be immutable may be assessed more critically. Regulatory track record analysis is therefore both a diligence exercise and pre-emptive litigation preparation.
        </div>

        <h3>The "take-and-pay" trap</h3>
        <p>A specific variant of FET risk that is underappreciated in African project finance is the distinction between <strong>take-or-pay</strong> and <strong>take-and-pay</strong> obligations in PPAs. A genuine take-or-pay clause obligates the state utility to pay for the contracted energy volume whether or not it is actually dispatched — providing the investor with payment certainty regardless of grid conditions. A take-and-pay clause, by contrast, only triggers payment when the utility actually takes the power. In markets with grid reliability problems — which characterise a significant portion of sub-Saharan Africa — a take-and-pay structure leaves the investor exposed to dispatch risk that the PPA was supposed to eliminate.</p>
        <p>Where a state utility consistently fails to dispatch — either because the grid cannot accommodate the generation or because the utility is deliberately avoiding its payment obligation — the investor may have a viable FET claim if it can establish that the state's failure to maintain grid infrastructure or honour dispatch obligations constitutes a targeted frustration of the investment. The treaty layer does not replace the contractual analysis but may provide the enforcement mechanism when the contractual remedy is nominal.</p>

        <div class="pullquote">
          The question a tribunal asks is not whether the regulatory change harmed the investment. It is whether the state made a specific commitment that the change would not happen — and whether that commitment was what brought the investor to the table.
        </div>
      </section>

      <!-- SECTION 3 -->
      <section id="expropriation">
        <h2>Indirect Expropriation vs. the Police Powers Doctrine</h2>
        <p>The boundary between a legitimate environmental or energy regulation and an indirect expropriation requiring compensation is where the most consequential African energy disputes will be resolved over the next decade. The stakes are significant on both sides: for investors, the ability to recover capital and projected returns; for states, the ability to pursue the energy transition without every regulatory adjustment triggering an international arbitration.</p>

        <h3>The substantial deprivation threshold</h3>
        <p>To establish indirect expropriation, the investor must generally demonstrate that the state measure has substantially deprived the investment of its economic value — not merely reduced profit margins or increased operating costs. The standard most commonly applied requires near-total neutralisation of the investment's value, though the precise threshold varies by treaty and tribunal. A feed-in tariff reduction that makes a project less profitable does not ordinarily constitute expropriation. A tariff elimination that renders the project economically non-viable, combined with a refusal to permit renegotiation, more plausibly does.</p>

        <h3>How the police powers doctrine is deployed in African disputes</h3>
        <p>African states defending against indirect expropriation claims have increasingly invoked the <strong>police powers doctrine</strong> — the principle that a state's non-discriminatory, proportionate regulation in pursuit of a legitimate public interest does not constitute expropriation requiring compensation, even if it substantially harms the investor. In the energy context, this encompasses new grid balancing requirements, revised carbon tax frameworks, adjustments to renewable energy procurement targets, and environmental licensing changes.</p>
        <p>The doctrine creates a genuine analytical difficulty because the Paris Agreement and national NDC commitments give states a strong public interest narrative for almost any energy sector regulation. The critical battleground is therefore not the legitimacy of the regulatory objective but whether the specific measure was <strong>discriminatory</strong> — targeting the foreign investor in ways that domestic operators are not subject to — and whether it was <strong>proportionate</strong> to the stated objective. A grid priority change that applies equally to all generators is significantly harder to challenge than one that specifically disadvantages foreign-owned independent power producers.</p>

        <div class="takeaway">
          Deemed generation clauses in PPAs address one manifestation of this problem by entitling the investor to payment for contracted capacity even when the grid operator does not dispatch. Their interaction with the treaty layer is underexamined: a state that systematically instructs its utility to invoke deemed generation provisions rather than addressing the underlying grid failure may be accumulating exposure to a broader treaty claim that the contractual mechanism was never designed to absorb.
        </div>
      </section>

      <!-- SECTION 4 -->
      <section id="afcfta">
        <h2>The AfCFTA Investment Protocol: A Structural Shift</h2>
        <p>The AfCFTA Investment Protocol — which entered the implementation phase from 2024 — represents the most significant restructuring of the African investment law framework since the proliferation of bilateral BITs in the 1990s and 2000s. For renewable energy investors, it has four consequences that require analysis before a new project is structured.</p>

        <div class="audit-grid">
          <div class="audit-card">
            <div class="audit-tag">01</div>
            <div>
              <div class="audit-title">Investor obligations are affirmative</div>
              <p class="audit-body">Unlike older BITs, which almost exclusively addressed state obligations, the AfCFTA Protocol imposes direct obligations on investors covering environmental compliance, anti-corruption, human rights due diligence, and technology transfer. Breach of these obligations may provide the host state with a counterclaim defence in arbitration — a mechanism that was theoretically available before but rarely used with structured treaty support.</p>
              <p class="audit-question">Have you mapped your project's supply chain and construction practices against the Protocol's investor obligation framework?</p>
            </div>
          </div>
          <div class="audit-card">
            <div class="audit-tag">02</div>
            <div>
              <div class="audit-title">The umbrella clause is narrowed or absent</div>
              <p class="audit-body">Many older bilateral BITs contain an umbrella clause that elevates contractual obligations (including PPA commitments) to the treaty level — converting a commercial breach by a state utility into an internationally arbitrable treaty claim. The AfCFTA Protocol does not include a broad umbrella clause. PPA breaches by state utilities in Protocol-governed disputes will ordinarily remain domestic contract disputes unless they rise to the level of a denial of justice or an FET violation in their own right.</p>
              <p class="audit-question">Does your applicable treaty contain an umbrella clause? Does it cover obligations under "written contracts" only, or any state commitment?</p>
            </div>
          </div>
          <div class="audit-card">
            <div class="audit-tag">03</div>
            <div>
              <div class="audit-title">The right to regulate is explicitly preserved</div>
              <p class="audit-body">The Protocol explicitly recognises the host state's right to regulate in the public interest — including for environmental protection and the energy transition. This does not eliminate FET or expropriation claims but narrows the space in which they succeed. Measures that are non-discriminatory, proportionate, and directed at a legitimate public interest objective will be harder to challenge under the Protocol than under older BITs with more investor-protective language.</p>
              <p class="audit-question">If your host state invokes the right-to-regulate defence, which specific aspect of your treaty's FET definition limits that right?</p>
            </div>
          </div>
          <div class="audit-card">
            <div class="audit-tag">04</div>
            <div>
              <div class="audit-title">Older bilateral BITs may still apply</div>
              <p class="audit-body">The Protocol does not automatically supersede existing bilateral BITs between AfCFTA member states. An investor structured through a jurisdiction with an older, more protective bilateral BIT with the host state may retain access to that instrument. Whether this constitutes impermissible treaty shopping — and how the Protocol's relationship with existing BITs is resolved — will be determined by arbitral tribunals in the coming years. The legal position is genuinely unsettled and must be assessed jurisdiction by jurisdiction.</p>
              <p class="audit-question">Is there an older BIT between your holding company's jurisdiction and the host state that provides broader protection than the Protocol?</p>
            </div>
          </div>
        </div>
      </section>

