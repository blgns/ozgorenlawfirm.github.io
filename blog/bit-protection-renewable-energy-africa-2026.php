      <section id="two-layers">
        <h2>The Hierarchy of Protection: PPA vs. BIT</h2>
        <p>Every cross-border renewable energy project in Africa sits within two distinct legal frameworks simultaneously. The first is contractual: the Power Purchase Agreement, the EPC contract, the grid connection agreement — all governed by the host state's domestic law, interpreted by domestic courts, and enforced through domestic institutions. The second is the treaty layer: the applicable Bilateral Investment Treaty or multilateral instrument, which operates under public international law and provides access to international arbitration before forums that the host state cannot control.</p>
        <p>These two layers are not alternatives. They address different risks. The PPA protects against non-payment, technical failure, and breach of specific contractual commitments. The BIT protects against state conduct that falls outside the contract — regulatory changes, discriminatory treatment, creeping expropriation, and denial of justice. The distinction matters enormously in practice because the most serious threats to long-term African renewable energy projects are typically not commercial disputes between private parties but regulatory shifts driven by political priorities, currency crises, or energy policy reversals at the state level.</p>

