        <h2>Frequently Asked Questions</h2>

        <div class="faq-list">
          <div class="faq-item">
            <button class="faq-btn" aria-expanded="false">
              What is the difference between PPA protection and BIT protection for a renewable energy project in Africa?
              <span class="faq-icon">+</span>
            </button>
            <div class="faq-answer">
              A Power Purchase Agreement is a commercial contract governed by the host state's domestic law. It protects the investor against non-payment, technical failure, and contractual breach — but its enforcement depends on local courts, which may not be independent of the state entity that is the counterparty.<br><br>
              A Bilateral Investment Treaty operates at the level of public international law. It protects the investor against state <em>conduct</em> that undermines the investment — including regulatory changes, discriminatory treatment, expropriation without compensation, and denial of justice. BIT claims go before international arbitral tribunals under international law, bypassing the host state's domestic legal system. The two instruments address complementary risks; neither substitutes for the other.
            </div>
          </div>

          <div class="faq-item">
            <button class="faq-btn" aria-expanded="false">
              What is the FET standard and how does it apply to renewable energy disputes in Africa?
              <span class="faq-icon">+</span>
            </button>
            <div class="faq-answer">
              The Fair and Equitable Treatment standard requires the host state to treat foreign investors fairly and without arbitrariness. In renewable energy disputes, FET claims most commonly arise when: a state cuts or eliminates a feed-in tariff after the investor has committed capital; regulatory changes increase costs or reduce revenues in ways the investor could not have anticipated; or a state utility refuses to honour its take-or-pay obligation and local courts provide no effective remedy.<br><br>
              Modern tribunals require <strong>specific, targeted state assurances</strong> — not merely a general expectation of regulatory stability — to establish a legitimate expectation cognisable under FET. Investors must document those assurances at the time they are made, not after the dispute has arisen.
            </div>
          </div>

          <div class="faq-item">
            <button class="faq-btn" aria-expanded="false">
              What is the difference between a freezing clause and an economic equilibrium clause in a PPA?
              <span class="faq-icon">+</span>
            </button>
            <div class="faq-answer">
              A <strong>freezing clause</strong> attempts to lock the legal framework in place at the time of contracting — preventing the host state from applying subsequent laws to the project. These clauses are increasingly unenforceable as courts and tribunals recognise states' regulatory sovereignty.<br><br>
              An <strong>economic equilibrium clause</strong> (also called an economic stabilisation clause) takes a different approach: it allows the law to change but requires the state to compensate the investor for any cost increase or revenue reduction that results. Economic equilibrium clauses are considered more commercially durable and more likely to be upheld in both domestic courts and international arbitration. They also interact more productively with the treaty layer, because the state's refusal to honour the equilibrium obligation may itself constitute an FET violation or umbrella clause breach.
            </div>
          </div>

          <div class="faq-item">
            <button class="faq-btn" aria-expanded="false">
              Does the AfCFTA Investment Protocol change the protection available to renewable energy investors in Africa?
              <span class="faq-icon">+</span>
            </button>
            <div class="faq-answer">
              Yes, significantly. Unlike older bilateral BITs, the AfCFTA Investment Protocol explicitly balances investor protections with investor obligations — including environmental compliance, anti-corruption standards, and human rights due diligence. It preserves a broader right to regulate for host states and omits or narrows several protections found in older BITs, including umbrella clauses and broad definitions of indirect expropriation.<br><br>
              Investors structuring new projects in AfCFTA member states need to assess whether the Protocol applies, whether an older bilateral BIT provides stronger protection, and whether structuring through a jurisdiction with a more protective bilateral BIT is available and defensible.
            </div>
          </div>

          <div class="faq-item">
            <button class="faq-btn" aria-expanded="false">
              What is the police powers doctrine and how do African states use it to defend against expropriation claims?
              <span class="faq-icon">+</span>
            </button>
            <div class="faq-answer">
              The police powers doctrine holds that a state's non-discriminatory, proportionate regulatory measures — enacted in good faith to pursue legitimate public interest objectives — do not constitute expropriation requiring compensation, even if they significantly harm an investment's value.<br><br>
              In African energy disputes, states invoke this doctrine to defend changes in grid priority rules, new carbon taxes, revised licensing requirements, and adjustments to renewable energy procurement targets. The critical questions are whether the measure was <strong>discriminatory</strong> (targeting foreign investors specifically) and whether it was <strong>proportionate</strong> to its stated objective. Discriminatory or disproportionate measures are significantly more vulnerable to expropriation claims even where the underlying regulatory objective is legitimate.
            </div>
          </div>
        </div>
      </section>

