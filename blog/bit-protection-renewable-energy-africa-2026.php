      <section id="cooling-off">
        <h2>The Cooling-Off Period as a Negotiating Instrument</h2>
        <p>Most BITs require a mandatory negotiation or cooling-off period — typically six months — between the investor's notice of dispute and the filing of a Request for Arbitration. Standard legal practice treats this as a procedural formality: a waiting period before the real proceedings begin. That framing misses the instrument's strategic utility.</p>
        <p>The cooling-off period is the only phase of an investment dispute in which both parties share a strong incentive to avoid the cost and reputational exposure of formal arbitration. For the state, an arbitration notice from a foreign investor creates diplomatic and credit rating exposure — particularly in states that are actively raising project finance for new energy infrastructure. For the investor, the cost and time of formal proceedings are real constraints, particularly for smaller independent power producers.</p>
        <p>A well-deployed cooling-off period can accomplish several things that formal arbitration cannot: it allows the parties to restructure the PPA on commercially sustainable terms without the adjudicative pressure of an ongoing proceeding; it permits the state to introduce a modified regulatory framework that addresses the investor's concern while preserving political flexibility; and it creates a documented record of the state's negotiating position that will be directly relevant if the matter does proceed to a tribunal.</p>

        <ul class="checklist">
          <li>
            <strong>File a notice of dispute that is precise and legally complete</strong>
            The notice serves a dual purpose: it formally triggers the cooling-off period and establishes the legal basis for the treaty claim. A vague notice that fails to identify the specific treaty violations with precision weakens the investor's negotiating position and may create jurisdictional problems later. The notice should be drafted with the same rigour as a Request for Arbitration.
          </li>
          <li>
            <strong>Identify the economic equilibrium mechanism in the PPA and propose a correction formula</strong>
            Rather than demanding restoration of the original regulatory framework — which the state may be politically unable to deliver — the investor should identify the economic equilibrium clause, quantify the impact of the regulatory change, and propose a compensation formula or tariff adjustment that restores the project's financial model. This reframes the dispute from a legal confrontation to a commercial negotiation.
          </li>
          <li>
            <strong>Use the period to preserve evidence</strong>
            Contemporaneous documents — regulatory communications, government statements, grid operator instructions, correspondence with the state utility — are the evidentiary foundation of any FET or expropriation claim. The cooling-off period is the time to secure and organise this evidence before it becomes subject to litigation privilege disputes or practical access difficulties.
          </li>
          <li>
            <strong>Monitor for additional regulatory measures that may widen the claim</strong>
            States that are under financial pressure in the energy sector frequently introduce a sequence of incremental measures — what practitioners sometimes call regulatory drips — rather than a single decisive change. Each measure individually may fall below the FET or expropriation threshold. Cumulatively, they may not. The cooling-off period is when this pattern crystallises, and the investor should document it systematically.
          </li>
        </ul>
      </section>

      <!-- SECTION 6 -->
      <section id="bit-audit">
        <h2>Four BIT Provisions That Determine Investment Recovery</h2>
        <p>When reviewing the treaty framework for a project or a dispute, four provisions have the greatest practical impact on the investor's ability to recover. They are not equally present across all treaties — and their specific drafting, not their presence or absence alone, determines their utility.</p>

        <div class="audit-grid">
          <div class="audit-card">
            <div class="audit-tag">FET</div>
            <div>
              <div class="audit-title">FET definition — autonomous standard or minimum standard?</div>
              <p class="audit-body">BITs define FET either as an autonomous treaty standard (which tribunals interpret independently) or by reference to the customary international law minimum standard of treatment. The latter is significantly harder to satisfy — it requires conduct so egregious as to shock the conscience of the international community. Modern African BITs vary considerably on this point. The distinction can be outcome-determinative in cases involving regulatory changes that are arguably defensible but commercially harmful.</p>
              <p class="audit-question">Does the BIT's FET clause reference the minimum standard of treatment, or is it an autonomous standard?</p>
            </div>
          </div>
          <div class="audit-card">
            <div class="audit-tag">UC</div>
            <div>
              <div class="audit-title">Umbrella clause — scope of coverage</div>
              <p class="audit-body">Where present, an umbrella clause elevates the host state's contractual obligations to the treaty level. The critical drafting question is whether the clause covers "any obligation" the state has assumed toward the investor, or only "written contracts" or "specific commitments." A narrowly drafted clause may not cover grid connection commitments, regulatory approvals, or oral assurances from government officials — the very instruments on which FET legitimate expectations claims are often built.</p>
              <p class="audit-question">Does the umbrella clause cover the state utility's PPA obligations? Does it extend to regulatory licences and approvals?</p>
            </div>
          </div>
          <div class="audit-card">
            <div class="audit-tag">SS</div>
            <div>
              <div class="audit-title">Survival (sunset) clause — post-termination protection</div>
              <p class="audit-body">Most BITs include a survival clause providing that investor protections continue for a fixed period — typically ten to twenty years — after the treaty is terminated. The practical relevance has increased as several African states have terminated or failed to renew bilateral BITs in the context of treaty reform processes. An investor whose BIT is terminated after capital has been committed needs to know precisely how long the treaty's protection continues and what that protection covers.</p>
              <p class="audit-question">If the host state terminated this BIT today, how many years of treaty protection would remain for your existing investment?</p>
            </div>
          </div>
          <div class="audit-card">
            <div class="audit-tag">TF</div>
            <div>
              <div class="audit-title">Transfer of funds — currency and convertibility</div>
              <p class="audit-body">Renewable energy projects generate revenue in local currency but debt service and dividend payments require foreign exchange. The BIT's transfer of funds provision determines whether the investor can repatriate profits in a freely convertible currency without restriction. In states experiencing foreign exchange crises — a recurring feature of the African energy finance landscape — this provision may be the most immediately commercially relevant treaty protection, preceding any regulatory dispute.</p>
              <p class="audit-question">Does the BIT guarantee the right to repatriate profits in a freely convertible currency? Are there permitted exceptions for balance of payments emergencies?</p>
            </div>
          </div>
        </div>
      </section>

