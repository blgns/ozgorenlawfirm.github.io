      <!-- INTRO BOX -->
      <div class="intro-box">
        The Power Purchase Agreement is where lawyers spend most of their time. It is also where investors feel most protected. In practice, a PPA's enforceability depends entirely on the host state's legal system — the very institution that may be the source of the problem. <strong>The BIT is the instrument that operates when the state itself is the counterparty and the domestic legal order offers no independent remedy.</strong> Understanding how the two layers interact — and where one ends and the other begins — is the central structural question for any renewable energy project in Africa in 2026.
      </div>

